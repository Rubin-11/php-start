while (true) {
    echo "Введите положительное число: ";
    $input = trim(fgets(STDIN));

    if (is_numeric($input) && $input > 0) {
        $n = (int)$input;
        break;
    } else {
        echo "Ошибка: введите корректное положительное число.\n";
    }
}

$position = ($n - 1) % 8;

